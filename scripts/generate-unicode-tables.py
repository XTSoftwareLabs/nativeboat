"""Generates crates/nativeboat-native/src/unicode_tables.rs from the Unicode
Character Database that ships with Python's `unicodedata` module.

The tables drive String.prototype.normalize (decompositions, canonical
combining classes and compositions), the Final_Sigma rule of
String.prototype.toLowerCase (case-ignorable characters) and the
punctuation/symbol class of String.prototype.localeCompare.

Run with the Python whose `unicodedata.unidata_version` matches the Unicode
version JavaScript engines use (15.1 for Node 22), then format with rustfmt:

    python scripts/generate-unicode-tables.py
"""

import os
import unicodedata

OUT = os.path.join(os.path.dirname(__file__), "..", "crates", "nativeboat-native", "src", "unicode_tables.rs")
HANGUL = range(0xAC00, 0xD7A4)


def ranges(predicate):
    found = []
    start = None
    for code in range(0x110000):
        inside = predicate(chr(code))
        if inside and start is None:
            start = code
        elif not inside and start is not None:
            found.append((start, code - 1))
            start = None
    if start is not None:
        found.append((start, 0x10FFFF))
    return found


def main():
    canonical, compat, data = [], [], []
    classes = []
    compositions = []
    for code in range(0x110000):
        if code in HANGUL:
            continue
        char = chr(code)
        combining = unicodedata.combining(char)
        if combining:
            classes.append((code, combining))
        decomposition = unicodedata.decomposition(char)
        if not decomposition:
            continue
        parts = decomposition.split()
        is_compat = parts[0].startswith("<")
        if is_compat:
            parts = parts[1:]
        points = [int(part, 16) for part in parts]
        entry = (code, len(data), len(points))
        data.extend(points)
        (compat if is_compat else canonical).append(entry)
        # A canonical pair composes back unless the character is excluded
        # from composition (singletons, non-starter decompositions and the
        # explicit exclusions), which NFC itself reveals.
        if not is_compat and len(points) == 2:
            pair = chr(points[0]) + chr(points[1])
            if unicodedata.normalize("NFC", pair) == char:
                compositions.append((points[0], points[1], code))
    compositions.sort()

    def category_ranges(categories):
        return ranges(lambda char: unicodedata.category(char) in categories)

    # Case_Ignorable: Mn, Me, Cf, Lm, Sk and the Word_Break MidLetter,
    # MidNumLet and Single_Quote characters.
    word_break = {0x27, 0x2E, 0x3A, 0xB7, 0x387, 0x55F, 0x5F4, 0x2018, 0x2019, 0x2024, 0x2027, 0xFE13, 0xFE52, 0xFE55, 0xFF07, 0xFF0E, 0xFF1A}
    ignorable = ranges(lambda char: unicodedata.category(char) in ("Mn", "Me", "Cf", "Lm", "Sk") or ord(char) in word_break)
    # Collation places whitespace, punctuation and symbols before digits and
    # letters (and lets ignorePunctuation skip them).
    punctuation = category_ranges(("Zs", "Zl", "Zp", "Pc", "Pd", "Ps", "Pe", "Pi", "Pf", "Po", "Sm", "Sc", "Sk", "So", "Cc", "Cf"))

    def rows(items, format_item, per_line=6):
        lines = []
        for start in range(0, len(items), per_line):
            lines.append("    " + " ".join(format_item(item) for item in items[start : start + per_line]))
        return "\n".join(lines)

    text = f"""//! Unicode {unicodedata.unidata_version} character data, generated by
//! `scripts/generate-unicode-tables.py` from the Unicode Character Database
//! (Unicode License v3; see `crates/nativeboat-start/src/NOTICES.txt`).
//! Do not edit by hand.

/// The Unicode version of these tables.
#[cfg(test)]
pub(crate) const VERSION: &str = "{unicodedata.unidata_version}";

/// Code points of decompositions, indexed by the decomposition tables.
pub(crate) static DECOMPOSITION_DATA: [u32; {len(data)}] = [
{rows(data, lambda point: f"0x{point:X},", 12)}
];

/// Canonical decompositions: code point, start in the data and length.
pub(crate) static CANONICAL: [(u32, u16, u8); {len(canonical)}] = [
{rows(canonical, lambda item: f"(0x{item[0]:X}, {item[1]}, {item[2]}),")}
];

/// Compatibility decompositions: code point, start in the data and length.
pub(crate) static COMPATIBILITY: [(u32, u16, u8); {len(compat)}] = [
{rows(compat, lambda item: f"(0x{item[0]:X}, {item[1]}, {item[2]}),")}
];

/// Nonzero canonical combining classes.
pub(crate) static COMBINING_CLASSES: [(u32, u8); {len(classes)}] = [
{rows(classes, lambda item: f"(0x{item[0]:X}, {item[1]}),", 8)}
];

/// Canonical compositions: first, second and composite code points.
pub(crate) static COMPOSITIONS: [(u32, u32, u32); {len(compositions)}] = [
{rows(compositions, lambda item: f"(0x{item[0]:X}, 0x{item[1]:X}, 0x{item[2]:X}),", 4)}
];

/// Case-ignorable code point ranges (inclusive).
pub(crate) static CASE_IGNORABLE: [(u32, u32); {len(ignorable)}] = [
{rows(ignorable, lambda item: f"(0x{item[0]:X}, 0x{item[1]:X}),", 6)}
];

/// Whitespace, punctuation, symbol and control code point ranges (inclusive).
pub(crate) static PUNCTUATION: [(u32, u32); {len(punctuation)}] = [
{rows(punctuation, lambda item: f"(0x{item[0]:X}, 0x{item[1]:X}),", 6)}
];
"""
    with open(OUT, "w", encoding="utf-8", newline="\n") as file:
        file.write(text)
    print(f"Unicode {unicodedata.unidata_version}: {len(canonical)} canonical, {len(compat)} compatibility, "
          f"{len(classes)} combining classes, {len(compositions)} compositions, "
          f"{len(ignorable)} case-ignorable and {len(punctuation)} punctuation ranges")


main()


def vectors():
    """Test vectors: random strings across scripts and their four forms."""
    import random

    random.seed(1517)
    pools = [range(0x20, 0x7F), range(0xA0, 0x250), range(0x300, 0x370), range(0x370, 0x400),
             range(0x400, 0x530), range(0x1E00, 0x1F00), range(0x1F00, 0x2000), range(0x2000, 0x2200),
             range(0x3040, 0x3100), range(0x1100, 0x1200), range(0xAC00, 0xAC40), range(0xFB00, 0xFB50),
             range(0xFF00, 0xFFF0), range(0x0E00, 0x0E80), range(0x0900, 0x0980), range(0x1D400, 0x1D500)]
    lines = []
    for _ in range(3000):
        text = "".join(chr(random.choice(random.choice(pools))) for _ in range(random.randint(1, 8)))
        forms = [unicodedata.normalize(form, text) for form in ("NFC", "NFD", "NFKC", "NFKD")]
        lines.append("\t".join(" ".join(f"{ord(c):X}" for c in value) for value in [text] + forms))
    path = os.path.join(os.path.dirname(OUT), "unicode", "vectors.txt")
    with open(path, "w", encoding="utf-8", newline="\n") as file:
        file.write("\n".join(lines) + "\n")


vectors()
