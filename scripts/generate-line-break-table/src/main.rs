//! Writes `crates/nativeboat-layout/src/line_break/table.rs`, the Unicode
//! line breaking class of every code point, to standard output:
//!
//! ```text
//! cargo run --release --manifest-path scripts/generate-line-break-table/Cargo.toml \
//!     > crates/nativeboat-layout/src/line_break/table.rs
//! ```
//!
//! The class order must match `nativeboat_layout::line_break::Class`.

use icu_properties::props::{EastAsianWidth, LineBreak};
use icu_properties::{CodePointMapData, PropertyNamesShort};

/// The classes in the order of `Class`.
const ORDER: [&str; 40] = [
    "AL", "B2", "BA", "BB", "BK", "CB", "CL", "CM", "CP", "CPW", "CR", "EB", "EM", "EX", "GL", "H2",
    "H3", "HL", "HY", "ID", "IN", "IS", "JL", "JT", "JV", "LF", "NL", "NS", "NU", "OP", "OPW", "PO",
    "PR", "QU", "RI", "SP", "SY", "WJ", "ZW", "ZWJ",
];

fn main() {
    let classes = CodePointMapData::<LineBreak>::new();
    let widths = CodePointMapData::<EastAsianWidth>::new();
    let names = PropertyNamesShort::<LineBreak>::new();
    let mut ranges: Vec<(u32, &str)> = Vec::new();
    for code in 0u32..=0x10FFFF {
        let name = names.get(classes.get32(code)).unwrap_or("XX");
        // LB1's resolutions, and approximations of LB20a and LB28a.
        let name = match name {
            "AI" | "SG" | "XX" | "SA" | "AK" | "AP" | "AS" | "VF" | "VI" => "AL",
            "CJ" => "NS",
            "HH" => "BA",
            other => other,
        };
        let wide = matches!(
            widths.get32(code),
            EastAsianWidth::Fullwidth | EastAsianWidth::Wide | EastAsianWidth::Halfwidth
        );
        let name = match name {
            "OP" if wide => "OPW",
            "CP" if wide => "CPW",
            other => other,
        };
        assert!(ORDER.contains(&name), "unexpected class {name}");
        if ranges.last().is_none_or(|(_, last)| *last != name) {
            ranges.push((code, name));
        }
    }
    let mut out = String::new();
    out.push_str("// Unicode Line_Break classes from ICU4X icu_properties 2.3.0's data,\n");
    out.push_str("// resolved as UAX #14's LB1 says, with wide OP and CP marked by their\n");
    out.push_str("// East_Asian_Width (Unicode License v3; see\n");
    out.push_str("// `crates/nativeboat-start/src/NOTICES.txt`). Generated by\n");
    out.push_str("// `scripts/generate-line-break-table`; do not edit by hand.\n\n");
    out.push_str("/// Each range's first code point, shifted left eight bits, and its class.\n");
    out.push_str(&format!("pub(super) static RANGES: [u32; {}] = [\n", ranges.len()));
    for chunk in ranges.chunks(6) {
        out.push_str("   ");
        for (start, name) in chunk {
            let index = ORDER.iter().position(|class| class == name).unwrap();
            out.push_str(&format!(" 0x{:X},", (start << 8) | index as u32));
        }
        out.push('\n');
    }
    out.push_str("];\n");
    print!("{out}");
}
